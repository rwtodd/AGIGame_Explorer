  /// Draws a single character glyph at pixel coordinates `(x, y)` on the canvas in the specified EGA foreground color.
  static void drawChar(Canvas canvas, int asciiCode, double x, double y, int fgColorIndex) {
    if (asciiCode < firstAscii || asciiCode > lastAscii) {
      asciiCode = 127;
    }
    final charOffset = (asciiCode - firstAscii) * 8;
    final paint = Paint()
      ..color = EgaColors.palette[fgColorIndex.clamp(0, 15)]
      ..style = PaintingStyle.fill;

    for (int row = 0; row < 8; row++) {
      final byte = fontData[charOffset + row];
      if (byte == 0) continue;

      int startBit = -1;
      for (int bit = 0; bit < 8; bit++) {
        final isSet = ((byte >> (7 - bit)) & 1) != 0;
        if (isSet) {
          if (startBit == -1) startBit = bit;
        } else {
          if (startBit != -1) {
            canvas.drawRect(
              Rect.fromLTWH(x + startBit, y + row, (bit - startBit).toDouble(), 1.0),
              paint,
            );
            startBit = -1;
          }
        }
      }
      if (startBit != -1) {
        canvas.drawRect(
          Rect.fromLTWH(x + startBit, y + row, (8 - startBit).toDouble(), 1.0),
          paint,
        );
      }
    }
  }
